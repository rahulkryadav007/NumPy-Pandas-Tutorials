import numpy as np  # NumPy library import kar rahe hain

# Pehla NumPy array create kar rahe hain
a = np.array([10, 20, 30])

# Doosra NumPy array create kar rahe hain
b = np.array([1, 2, 3])

print("Addition:", a + b)  # Same index ke elements ko add
print("Subtraction:", a - b)  # Same index ke elements ko subtract
print("Multiplication:", a * b)  # Same index ke elements ko multiply
print("Division:", a / b)  # Same index ke elements ko divide