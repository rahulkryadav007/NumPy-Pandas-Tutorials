import numpy as np  # NumPy library import kar rahe hain

# Numbers ka NumPy array create kar rahe hain
arr = np.array([10, 20, 30])

print("Addition:", arr + 5)  # Har element mein 5 add
print("Subtraction:", arr - 5)  # Har element se 5 subtract
print("Multiplication:", arr * 2)  # Har element ko 2 se multiply
print("Division:", arr / 2)  # Har element ko 2 se divide
print("Square:", arr ** 2)  # Har element ka square